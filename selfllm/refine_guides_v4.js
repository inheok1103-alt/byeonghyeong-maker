/* v4 — Ray's Drill 신판 흡수: 어법 3공리 해설체계(AI_GRAMMAR_CORE_LOGIC_V1) + 지문 클러스터 정책 V2 + 전체문장배열 신설.
   재실행 안전(◆공리/◆클러스터 marker). */
var fs = require("fs");
var P = __dirname + "/../knowledge/types_v2.json";
var d = JSON.parse(fs.readFileSync(P, "utf8")); var ts = d.types || d;

var AXIOM = " ◆공리(어법 해설체계): 모든 문법 해설은 3공리로 서술 — ①위치공리(자리가 역할을 결정: 주어 자리 데이터=명사 취급) ②경제성공리(반복 명사·뻔한 주어·예측 가능한 접속사/be는 압축된다: 관계사·분사구문·생략의 존재 이유) ③데이터보존공리(압축해도 주체 차이·시제 차이·이동 흔적은 형태로 보존 — having p.p., 의미상 주어, 좌초 전치사). 해설 순서: 원리 정의(암기규칙 금지)→IF-THEN 데이터 과정→학생 함정 방어→한국 교육과정 용어 매칭(예: valency→5형식, movement→수동태). 금지: '그냥 외워야 한다', 원리 없이 '자연스럽다'로 끝내기. 오답 설계 모듈: 발렌시(자동사 뒤 목적어 꽂기)·시제/가정법(과거형=단순 과거로만 오독 유도)·절축약(주어 다른데 분사구문·완료 시제 표지 누락)·관계화(선행사 없는 자리에 what)·이동/생략(도치 수일치·주격관계사+be 복원 실패).";
var CLUSTER = " ◆클러스터(지문 클러스터 정책): 지문은 1회만 제시하고 그 아래 1~3문항을 묶는다(문항마다 지문 재제시 금지). 조작(빈칸·삽입 제거·오류 주입)은 공통지문 자체에 반영. 같은 클러스터에서 빈칸+삽입+순서를 동시에 걸지 않는다. 앞 문항의 선지가 뒷 문항의 답을 노출하면 실패. 3문항이 모두 같은 근거 문장만 보게 하면 실패. 추천 조합: 핵심주장 지문=주제+내용일치+주제문서술형 / 대조=빈칸+불일치+요약 / 인과=일치+어법+서술형 / 문법 강한 지문=어법+이해+어법교정서술형.";

var n = 0;
ts.forEach(function (t) {
  var g = t.guide || "";
  if (/어법|어형변형|틀린문장|문장전환/.test(t.type) && g.indexOf("◆공리(") < 0) { t.guide = g + AXIOM; n++; g = t.guide; }
  if (/장문세트|복합세트|혼합통합형/.test(t.type) && g.indexOf("◆클러스터(") < 0) { t.guide = g + CLUSTER; n++; }
});

// 전체문장배열 신설 (ORDER_ALL_SENTENCES_MODE)
if (!ts.some(function (t) { return t.type === "전체문장배열"; })) {
  ts.push({
    type: "전체문장배열", on: true, cat: "간접쓰기",
    instruction: "다음 글의 모든 문장을 글의 흐름에 맞게 배열한 것으로 가장 적절한 것은?",
    guide: "ORDER_ALL_SENTENCES_MODE(Ray 신설): 지문의 모든 문장을 ①~⑥으로 번호화해 뒤섞고 전체 배열 순서를 묻는다. ◆적용조건: 5~9문장, 버리는 문장 0개(모든 문장이 정답 배열에 포함), 연결어·지시어·예시-일반화·인과 단서가 3개 이상 실존. ◆방법론: 첫 문장(일반 진술·화제 도입)을 확정하고 지시어(This/They)·정관사·담화표지(For example/However/As a result) 연쇄로 유일 배열을 보장(코드 검증). 선지 5개=전체 배열 순열(정답 1개+국소적으로 두 문장만 자연스러운 함정 배열). 문장 길이가 지나치게 불균형하면 변형으로 조절. ◆해설: 각 연결 고리의 단서어를 순서대로 인용. ◆클러스터: 단독 1문항 유형(다른 조작과 같은 지문에 걸지 않음)." + AXIOM.split("◆공리")[0]
  });
  n++;
  console.log("전체문장배열 신설");
}
d.meta = d.meta || {}; d.meta.v4 = "어법 3공리 해설체계 + 클러스터 정책 V2 + 전체문장배열 — " + n + "건";
fs.writeFileSync(P, JSON.stringify(d, null, 1));
console.log("v4 주입:", n, "건 · 총 유형:", ts.length);
